use std::{collections::BTreeMap, env, error::Error, fs, path::PathBuf};

use neo_core::dto::*;
use ts_rs::{Config, TS, TypeVisitor};

fn main() -> Result<(), Box<dyn Error>> {
    let mut args = env::args_os().skip(1);
    let output = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("web/src/lib/api/types"));
    if args.next().is_some() {
        return Err("usage: neo-typegen [output-directory]".into());
    }
    let config = Config::new().with_out_dir(&output);
    let mut exported = Exported::new(&config);
    exported.export::<HealthResponse>()?;
    exported.export::<ReadyResponse>()?;
    exported.export::<VersionResponse>()?;
    exported.export::<ErrorResponse>()?;
    exported.export::<LoginRequest>()?;
    exported.export::<LoginResponse>()?;
    exported.export::<MediaTokenResponse>()?;
    exported.export::<PasswordRequest>()?;
    exported.export::<User>()?;
    exported.export::<Page<WorkSummary>>()?;
    exported.export::<ProgressRequest>()?;
    exported.export::<FinishRequest>()?;
    exported.export::<WorkDetail>()?;
    exported.export::<TrackFont>()?;
    exported.export::<RootCreateRequest>()?;
    exported.export::<RootUpdateRequest>()?;
    exported.export::<RootStatus>()?;
    exported.export::<ScanRequest>()?;
    exported.export::<ScanResponse>()?;
    exported.export::<CircleCount>()?;
    exported.export::<VaCount>()?;
    exported.export::<TagCount>()?;
    exported.export::<TagMergeRequest>()?;
    exported.export::<MetadataRequest>()?;
    exported.export::<MissingReport>()?;
    exported.export::<CleanupRequest>()?;
    exported.export::<CleanupResponse>()?;
    exported.export::<RefreshResponse>()?;
    exported.export::<TaskSnapshot>()?;
    exported.export::<PrepareRequest>()?;
    exported.export::<PrepareResponse>()?;
    exported.export::<Loudness>()?;
    exported.export::<UserSettings>()?;
    exported.export::<ServerSettings>()?;
    exported.export::<ProxyCheckResult>()?;
    exported.export::<ReviewInput>()?;
    exported.export::<Review>()?;
    exported.export::<Page<TaskSnapshot>>()?;
    exported.export::<DesktopState>()?;
    exported.export::<MediaControl>()?;
    exported.export::<ImportDiscovered>()?;
    exported.export::<ImportPreview>()?;
    exported.export::<ImportResult>()?;
    exported.export::<ImportFailure>()?;
    fs::write(output.join("index.ts"), exported.barrel())?;
    Ok(())
}

/// Exports types with their dependencies and remembers every file written,
/// so the barrel lists exactly this run's types and never a stale file.
struct Exported<'a> {
    config: &'a Config,
    /// TypeScript name to module path, sorted by name.
    types: BTreeMap<String, String>,
}

impl<'a> Exported<'a> {
    fn new(config: &'a Config) -> Self {
        Self {
            config,
            types: BTreeMap::new(),
        }
    }

    fn export<T: TS + 'static>(&mut self) -> Result<(), Box<dyn Error>> {
        T::export_all(self.config)?;
        self.visit::<T>();
        Ok(())
    }

    fn barrel(&self) -> String {
        let mut source =
            String::from("// Generated by neo-typegen. Do not edit this file manually.\n");
        for (name, module) in &self.types {
            source.push_str(&format!("export type {{ {name} }} from './{module}';\n"));
        }
        source
    }
}

impl TypeVisitor for Exported<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Primitives have no output file and are not exported.
        let Some(path) = T::output_path() else {
            return;
        };
        let module = path.with_extension("").to_string_lossy().into_owned();
        if self.types.insert(T::ident(self.config), module).is_none() {
            T::visit_dependencies(self);
        }
    }
}
