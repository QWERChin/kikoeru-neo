-- The PostgreSQL schema as of SQLite migration 0009. Later migrations keep
-- the same number on both backends, so one version names one schema.
-- Mapping rules (book/src/data-model.md, "PostgreSQL"): integers are
-- BIGINT so every column decodes to i64 on both backends, flags are
-- BOOLEAN, text compares bytewise with COLLATE "C" like SQLite's BINARY,
-- and AUTOINCREMENT keys are identities that still accept explicit IDs.

CREATE TABLE roots (
  id                TEXT COLLATE "C" PRIMARY KEY,
  display_name      TEXT COLLATE "C" NOT NULL,
  last_scan_at      BIGINT,
  status            TEXT COLLATE "C" NOT NULL DEFAULT 'unknown',
  last_scan_end_at  BIGINT
);

CREATE TABLE circles (id BIGINT PRIMARY KEY, name TEXT COLLATE "C" NOT NULL);
CREATE TABLE vas     (id TEXT COLLATE "C" PRIMARY KEY, name TEXT COLLATE "C" NOT NULL);
CREATE TABLE tags    (id BIGINT PRIMARY KEY, name TEXT COLLATE "C" NOT NULL);
CREATE TABLE tag_aliases (
  alias   TEXT COLLATE "C" PRIMARY KEY,
  tag_id  BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE
);

CREATE TABLE works (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT COLLATE "C" NOT NULL UNIQUE,
  title         TEXT COLLATE "C" NOT NULL,
  circle_id     BIGINT REFERENCES circles(id),
  release_date  TEXT COLLATE "C",
  nsfw          BOOLEAN NOT NULL DEFAULT FALSE,
  dl_count      BIGINT,
  price         BIGINT,
  rate_average  DOUBLE PRECISION,
  rate_count    BIGINT,
  metadata_src  TEXT COLLATE "C" NOT NULL,
  cover_src     TEXT COLLATE "C" NOT NULL DEFAULT 'none',
  cover_version BIGINT NOT NULL DEFAULT 0,
  extra         TEXT COLLATE "C" NOT NULL DEFAULT '{}',
  missing_at    BIGINT,
  created_at    BIGINT NOT NULL,
  updated_at    BIGINT NOT NULL
);

CREATE TABLE work_locations (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_id       BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  root_id       TEXT COLLATE "C" NOT NULL REFERENCES roots(id),
  rel_path      BYTEA NOT NULL,
  display_path  TEXT COLLATE "C" NOT NULL,
  listing_hash  TEXT COLLATE "C",
  listed_at     BIGINT,
  missing_at    BIGINT,
  UNIQUE (root_id, rel_path)
);
CREATE INDEX work_locations_work ON work_locations (work_id);

CREATE TABLE work_vas  (work_id BIGINT REFERENCES works(id) ON DELETE CASCADE,
                        va_id   TEXT COLLATE "C" REFERENCES vas(id) ON DELETE CASCADE,
                        PRIMARY KEY (work_id, va_id));
CREATE TABLE work_tags (work_id BIGINT REFERENCES works(id) ON DELETE CASCADE,
                        tag_id  BIGINT REFERENCES tags(id)  ON DELETE CASCADE,
                        PRIMARY KEY (work_id, tag_id));

CREATE TABLE tracks (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_id       BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  location_id   BIGINT NOT NULL REFERENCES work_locations(id) ON DELETE CASCADE,
  rel_path      BYTEA NOT NULL,
  display_path  TEXT COLLATE "C" NOT NULL,
  sort_key      TEXT COLLATE "C" NOT NULL,
  kind          TEXT COLLATE "C" NOT NULL,
  size          BIGINT,
  mtime         BIGINT,
  duration_ms   BIGINT,
  duration_src  TEXT COLLATE "C",
  probe         TEXT COLLATE "C",
  duplicate_of  BIGINT REFERENCES tracks(id),
  missing_at    BIGINT,
  UNIQUE (location_id, rel_path)
);
CREATE INDEX tracks_work_kind ON tracks (work_id, kind);

CREATE TABLE users (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT COLLATE "C" NOT NULL UNIQUE,
  password_hash    TEXT COLLATE "C",
  is_admin         BOOLEAN NOT NULL DEFAULT FALSE,
  token_version    BIGINT NOT NULL DEFAULT 0,
  created_at       BIGINT NOT NULL
);

CREATE TABLE favorites (
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  work_id     BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  created_at  BIGINT NOT NULL,
  PRIMARY KEY (user_id, work_id)
);

CREATE TABLE play_progress (
  user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  work_id       BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  track_id      BIGINT REFERENCES tracks(id),
  position_ms   BIGINT NOT NULL DEFAULT 0,
  group_path    TEXT COLLATE "C",
  finished_at   BIGINT,
  replaying     BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at    BIGINT NOT NULL,
  PRIMARY KEY (user_id, work_id)
);

CREATE TABLE legacy_reviews (
  user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  work_id      BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  rating       BIGINT,
  review_text  TEXT COLLATE "C",
  progress     TEXT COLLATE "C",
  PRIMARY KEY (user_id, work_id)
);

CREATE TABLE import_pending (
  user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  work_id      BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  source       TEXT COLLATE "C" NOT NULL,
  durations    TEXT COLLATE "C",
  state        TEXT COLLATE "C" NOT NULL,
  PRIMARY KEY (user_id, work_id)
);

CREATE TABLE tasks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        TEXT COLLATE "C" NOT NULL,
  dedupe_key  TEXT COLLATE "C",
  state       TEXT COLLATE "C" NOT NULL,
  payload     TEXT COLLATE "C" NOT NULL,
  result      TEXT COLLATE "C",
  progress    DOUBLE PRECISION,
  message     TEXT COLLATE "C",
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);
CREATE UNIQUE INDEX tasks_active_dedupe ON tasks (dedupe_key)
  WHERE state IN ('queued', 'running');

CREATE TABLE tag_merges (
  from_id   BIGINT PRIMARY KEY,
  into_id   BIGINT NOT NULL,
  merged_at BIGINT NOT NULL
);

CREATE TABLE legacy_user_state (
  user_id            BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code               TEXT COLLATE "C" NOT NULL,
  favorite_at        BIGINT,
  has_review         BOOLEAN NOT NULL DEFAULT FALSE,
  rating             BIGINT,
  review_text        TEXT COLLATE "C",
  review_progress    TEXT COLLATE "C",
  progress_at        BIGINT,
  position_ms        BIGINT,
  finished_at        BIGINT,
  pending_source     TEXT COLLATE "C",
  pending_durations  TEXT COLLATE "C",
  pending_state      TEXT COLLATE "C",
  review_at          BIGINT,
  PRIMARY KEY (user_id, code)
);
CREATE INDEX legacy_user_state_code ON legacy_user_state (code);

CREATE TABLE root_settings (
  root_id     TEXT COLLATE "C" PRIMARY KEY REFERENCES roots(id),
  kind        TEXT COLLATE "C" NOT NULL CHECK (kind IN ('local', 'openlist', 'webdav')),
  settings    TEXT COLLATE "C" NOT NULL,
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);

CREATE TABLE track_analysis (
  track_id        BIGINT PRIMARY KEY REFERENCES tracks(id) ON DELETE CASCADE,
  size            BIGINT,
  mtime           BIGINT,
  integrated_lufs DOUBLE PRECISION,
  true_peak_dbtp  DOUBLE PRECISION,
  analyzed_at     BIGINT NOT NULL
);

CREATE TABLE user_settings (
  user_id            BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  normalize_loudness BOOLEAN NOT NULL DEFAULT FALSE,
  target_lufs        DOUBLE PRECISION NOT NULL DEFAULT -16,
  updated_at         BIGINT NOT NULL,
  accent             TEXT COLLATE "C"
    CHECK (accent IN ('blue', 'purple', 'pink', 'red', 'orange', 'green', 'teal', 'indigo'))
);

CREATE TABLE reviews (
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  work_id     BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  rating      BIGINT CHECK (rating BETWEEN 1 AND 5),
  text        TEXT COLLATE "C",
  updated_at  BIGINT,
  PRIMARY KEY (user_id, work_id),
  CHECK (rating IS NOT NULL OR text IS NOT NULL)
);
